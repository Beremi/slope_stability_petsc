"""Generate protocol schemas and language tables from one strict source."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
from typing import Any


GENERATOR_VERSION = "1"
CLANG_FORMAT_VERSION = "23.1.5"
ROOT = Path(__file__).resolve().parents[3]


def _json_bytes(value: Any) -> bytes:
    return (
        json.dumps(
            value,
            ensure_ascii=False,
            allow_nan=False,
            indent=2,
            sort_keys=True,
            separators=(",", ": "),
        )
        + "\n"
    ).encode("utf-8")


def _load_strict(path: Path) -> Any:
    def pairs(items: list[tuple[str, Any]]) -> dict[str, Any]:
        result: dict[str, Any] = {}
        for key, value in items:
            if key in result:
                raise ValueError(f"duplicate key {key!r} in {path}")
            result[key] = value
        return result

    with path.open("r", encoding="utf-8") as stream:
        return json.load(
            stream,
            object_pairs_hook=pairs,
            parse_constant=lambda value: (_ for _ in ()).throw(
                ValueError(f"nonfinite JSON number {value!r} in {path}")
            ),
        )


def _schema_for(kind_record: dict[str, Any], source: dict[str, Any]) -> dict[str, Any]:
    version = source["protocol_version"]
    required_sections = kind_record["required_sections"]
    envelope = source["common_envelope"]
    properties: dict[str, Any] = {
        "kind": {"const": kind_record["kind"]},
        "schema_version": {
            "type": "object",
            "additionalProperties": False,
            "required": ["major", "minor", "patch"],
            "properties": {
                "major": {"const": version["major"]},
                "minor": {"type": "integer", "minimum": 0},
                "patch": {"type": "integer", "minimum": 0},
            },
        },
        "id": {"type": "string", "pattern": envelope["id_pattern"]},
        "created_by": {
            "type": "object",
            "additionalProperties": False,
            "required": ["tool", "tool_version", "source_id"],
            "properties": {
                "tool": {"type": "string", "minLength": 1},
                "tool_version": {"type": "string", "minLength": 1},
                "source_id": {"type": "string", "minLength": 1},
            },
        },
        "provenance": {"type": "object"},
        "extensions": {
            "type": "object",
            "propertyNames": {"pattern": envelope["extension_key_pattern"]},
        },
    }
    section_schemas = kind_record.get("section_schemas", {})
    for section in [*required_sections, *kind_record.get("optional_sections", [])]:
        properties[section] = section_schemas.get(section, {"type": "object"})
    required = list(envelope["required"]) + [
        section for section in required_sections if section not in envelope["required"]
    ]
    schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": f"https://schemas.slope-stability.invalid/v1/{kind_record['schema_file']}",
        "title": kind_record["kind"],
        "type": "object",
        "additionalProperties": False,
        "required": required,
        "properties": properties,
    }
    if "all_of" in kind_record:
        schema["allOf"] = kind_record["all_of"]
    return schema


def _c_identifier(kind: str) -> str:
    return kind.replace(".", "_").replace("-", "_").upper()


def _emit_c_header(source: dict[str, Any]) -> bytes:
    lines = [
        "/* Protocol document kinds and their JSON Schema files, generated by",
        " * slope_codegen.protocol from schemas/source/protocol.json. Do not edit.",
        " * SPDX-License-Identifier: BSD-2-Clause",
        " */",
        "#ifndef SS_PROTOCOL_GENERATED_H",
        "#define SS_PROTOCOL_GENERATED_H",
        "",
        "#include <stddef.h>",
        "",
        f'#define SS_PROTOCOL_GENERATOR_VERSION "{GENERATOR_VERSION}"',
        f"#define SS_PROTOCOL_MAJOR {source['protocol_version']['major']}",
        f"#define SS_PROTOCOL_MINOR {source['protocol_version']['minor']}",
        f"#define SS_PROTOCOL_PATCH {source['protocol_version']['patch']}",
        "",
        "typedef enum {",
    ]
    for index, record in enumerate(source["artifact_kinds"], start=1):
        lines.append(f"  SS_KIND_{_c_identifier(record['kind'])} = {index},")
    lines.extend(
        [
            "} SsProtocolKind;",
            "",
            "typedef struct {",
            "  SsProtocolKind value;",
            "  const char *name;",
            "  const char *schema_file;",
            "} SsProtocolKindRecord;",
            "",
            "extern const SsProtocolKindRecord ss_protocol_kind_records[];",
            "extern const size_t ss_protocol_kind_record_count;",
            "",
            "#endif",
            "",
        ]
    )
    return "\n".join(lines).encode("utf-8")


def _emit_c_source(source: dict[str, Any]) -> bytes:
    lines = [
        "/* Protocol document-kind table, generated by slope_codegen.protocol",
        " * from schemas/source/protocol.json. Do not edit.",
        " * SPDX-License-Identifier: BSD-2-Clause",
        " */",
        '#include "ss_protocol_generated.h"',
        "",
        "const SsProtocolKindRecord ss_protocol_kind_records[] = {",
    ]
    for record in source["artifact_kinds"]:
        lines.append(
            '  {SS_KIND_%s, "%s", "%s"},'
            % (
                _c_identifier(record["kind"]),
                record["kind"],
                record["schema_file"],
            )
        )
    lines.extend(
        [
            "};",
            "",
            "const size_t ss_protocol_kind_record_count =",
            (
                "    sizeof(ss_protocol_kind_records) / "
                "sizeof(ss_protocol_kind_records[0]);"
            ),
            "",
        ]
    )
    return "\n".join(lines).encode("utf-8")


def _emit_python(source: dict[str, Any]) -> bytes:
    kinds = tuple(record["kind"] for record in source["artifact_kinds"])
    schemas = {
        record["kind"]: record["schema_file"] for record in source["artifact_kinds"]
    }
    text = (
        '"""Generated protocol constants. Do not edit by hand."""\n\n'
        "# SPDX-License-Identifier: BSD-2-Clause\n"
        "# Generated by slope_codegen.protocol.\n\n"
        f"PROTOCOL_VERSION = ({source['protocol_version']['major']}, "
        f"{source['protocol_version']['minor']}, "
        f"{source['protocol_version']['patch']})\n"
        f"ARTIFACT_KINDS = {kinds!r}\n"
        f"SCHEMA_FILES = {schemas!r}\n"
        f"ENUMS = {source['enums']!r}\n"
        f"FORBIDDEN_PUBLIC_KEYS = {tuple(source['forbidden_public_keys'])!r}\n"
    )
    return text.encode("utf-8")


def _format_c(payload: bytes, assumed_filename: Path) -> bytes:
    version = subprocess.run(
        ["clang-format", "--version"],
        check=False,
        capture_output=True,
        text=True,
    )
    if version.returncode != 0 or CLANG_FORMAT_VERSION not in version.stdout:
        raise RuntimeError(
            "protocol generation requires "
            f"clang-format {CLANG_FORMAT_VERSION}, observed {version.stdout.strip()!r}"
        )
    formatted = subprocess.run(
        [
            "clang-format",
            "--style=file",
            f"--assume-filename={assumed_filename}",
        ],
        input=payload,
        check=False,
        capture_output=True,
    )
    if formatted.returncode != 0:
        raise RuntimeError(
            "clang-format failed: " + formatted.stderr.decode("utf-8", errors="replace")
        )
    return formatted.stdout


def render(root: Path = ROOT) -> dict[Path, bytes]:
    from . import solver_options
    from .finite_elements import render_outputs as render_finite_elements

    source_path = root / "schemas/source/protocol.json"
    hdf5_path = root / "schemas/source/hdf5-layouts.json"
    conformance_path = root / "schemas/source/conformance.json"
    generator_path = root / "generators/src/slope_codegen/protocol.py"
    source = _load_strict(source_path)
    hdf5 = _load_strict(hdf5_path)
    conformance = _load_strict(conformance_path)
    options = solver_options.read_registry(root)
    solver_options.apply_schemas(source["artifact_kinds"], options)
    outputs: dict[Path, bytes] = {
        solver_options.PYTHON_SETTINGS: solver_options.render_python(options).encode(),
        solver_options.REFERENCE: solver_options.render_reference(options).encode(),
    }
    for record in source["artifact_kinds"]:
        outputs[Path("schemas/generated/json") / record["schema_file"]] = _json_bytes(
            _schema_for(record, source)
        )
    outputs[Path("schemas/hdf5-layout/generated-layouts.json")] = _json_bytes(hdf5)
    outputs[Path("schemas/fixtures/generated-conformance.json")] = _json_bytes(
        conformance
    )
    header_path = Path("generated/include/ss_protocol_generated.h")
    source_output_path = Path("generated/src/ss_protocol_generated.c")
    outputs[header_path] = _format_c(_emit_c_header(source), root / header_path)
    outputs[source_output_path] = _format_c(
        _emit_c_source(source), root / source_output_path
    )
    outputs[Path("python/src/slope_protocol/generated.py")] = _emit_python(source)
    finite_element_outputs, finite_element_sources = render_finite_elements(
        root, _format_c
    )
    outputs.update(finite_element_outputs)

    source_hashes = {
        str(path.relative_to(root)): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in (source_path, hdf5_path, conformance_path, generator_path)
    }
    for path in (
        solver_options.REGISTRY,
        Path("generators/src/slope_codegen/solver_options.py"),
    ):
        source_hashes[str(path)] = hashlib.sha256(
            (root / path).read_bytes()
        ).hexdigest()
    source_hashes.update(finite_element_sources)
    output_hashes = {
        str(path): hashlib.sha256(data).hexdigest()
        for path, data in sorted(outputs.items(), key=lambda item: str(item[0]))
    }
    manifest = {
        "schema_version": 1,
        "generator": "slope_codegen.protocol",
        "generator_version": GENERATOR_VERSION,
        "sources": source_hashes,
        "outputs": output_hashes,
    }
    outputs[Path("generated/manifest.json")] = _json_bytes(manifest)
    return outputs


def write_outputs(root: Path = ROOT) -> None:
    for relative, data in render(root).items():
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)


def check_outputs(root: Path = ROOT) -> list[str]:
    differences: list[str] = []
    for relative, expected in render(root).items():
        target = root / relative
        if not target.is_file():
            differences.append(f"missing {relative}")
        elif target.read_bytes() != expected:
            differences.append(f"changed {relative}")
    return differences


def clean_tree_reproducibility(root: Path = ROOT) -> list[str]:
    first = render(root)
    with tempfile.TemporaryDirectory(prefix="slope-protocol-generate-") as name:
        copy_root = Path(name) / "source"
        shutil.copytree(
            root,
            copy_root,
            ignore=shutil.ignore_patterns(".git", "build*", "__pycache__"),
        )
        second = render(copy_root)
    if first.keys() != second.keys():
        return ["generated output path set differs"]
    return [f"nondeterministic {path}" for path in first if first[path] != second[path]]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--reproducible", action="store_true")
    args = parser.parse_args(argv)
    if args.check:
        differences = check_outputs(args.root)
        for difference in differences:
            print(difference, file=sys.stderr)
        return 1 if differences else 0
    if args.reproducible:
        differences = clean_tree_reproducibility(args.root)
        for difference in differences:
            print(difference, file=sys.stderr)
        return 1 if differences else 0
    write_outputs(args.root)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
